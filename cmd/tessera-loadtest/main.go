// Params of a load test run.
type Params struct {
	URL          string
	APIKey       string
	Secret       string
	Rooms        int
	Publishers   int
	Subscribers  int
	AudioOnly    bool
	VideoLayers  int
	Duration     time.Duration
	RampUp       time.Duration
	ReportPeriod time.Duration
	JSON         string
	Loopback     bool
}

func main() {
	var p Params
	flag.StringVar(&p.URL, "url", "ws://localhost:7880", "server URL")
	flag.StringVar(&p.APIKey, "api-key", "devkey", "API key")
	flag.StringVar(&p.Secret, "secret", "", "API secret")
	flag.IntVar(&p.Rooms, "rooms", 1, "number of rooms")
	flag.IntVar(&p.Publishers, "publishers", 1, "publishers per room")
	flag.IntVar(&p.Subscribers, "subscribers", 0, "listen-only subscribers per room")
	flag.BoolVar(&p.AudioOnly, "audio-only", false, "publish audio only")
	flag.IntVar(&p.VideoLayers, "video-layers", 3, "simulcast layers per video track (1-3)")
	flag.DurationVar(&p.Duration, "duration", time.Minute, "test duration after ramp-up")
	flag.DurationVar(&p.RampUp, "ramp-up", 10*time.Second, "time to connect all clients")
	flag.DurationVar(&p.ReportPeriod, "report", 5*time.Second, "stats report period")
	flag.StringVar(&p.JSON, "json", "", "write the final report as JSON to this file")
	flag.BoolVar(&p.Loopback, "loopback", false, "restrict ICE to 127.0.0.1 (server with rtc.ips: [127.0.0.1])")
	flag.Parse()

	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	err := run(ctx, p)
	stop()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// magic marks payloads generated by the load tester.
var magic = [2]byte{'L', 'T'}

// Report is the final (and periodic) result.
type Report struct {
	Clients         int     `json:"clients"`
	ConnectFailures int     `json:"connect_failures"`
	JoinMsP50       float64 `json:"join_ms_p50"`
	JoinMsP95       float64 `json:"join_ms_p95"`
	FirstPacketP95  float64 `json:"first_packet_ms_p95"`
	RxPackets       uint64  `json:"rx_packets"`
	RxPPS           float64 `json:"rx_packets_per_sec"`
	RxMbps          float64 `json:"rx_mbps"`
	LossPercent     float64 `json:"loss_percent"`
	LatencyMsP50    float64 `json:"latency_ms_p50"`
	LatencyMsP99    float64 `json:"latency_ms_p99"`
	DurationSec     float64 `json:"duration_sec"`
}

type collector struct {
	rxPkts, rxBytes, lost, expected atomic.Uint64
	connectFail                     atomic.Int64
	mu                              sync.Mutex
	joins, firsts, latencies        []float64
}

func (c *collector) latency(ms float64) {
	c.mu.Lock()
	if len(c.latencies) < 200_000 {
		c.latencies = append(c.latencies, ms)
	}
	c.mu.Unlock()
}

func pct(v []float64, q float64) float64 {
	if len(v) == 0 {
		return 0
	}
	s := append([]float64(nil), v...)
	sort.Float64s(s)
	return s[min(len(s)-1, int(float64(len(s))*q))]
}

func run(ctx context.Context, p Params) error {
	if p.Secret == "" {
		return errs.New(errs.CodeInvalidArgument, "--secret is required")
	}
	if p.VideoLayers < 1 || p.VideoLayers > 3 {
		return errs.New(errs.CodeInvalidArgument, "--video-layers must be 1..3")
	}
	logger := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: slog.LevelWarn}))
	col := &collector{}
	total := p.Rooms * (p.Publishers + p.Subscribers)
	if total == 0 {
		return errs.New(errs.CodeInvalidArgument, "nothing to do")
	}
	gap := p.RampUp / time.Duration(total)
	runCtx, cancel := context.WithCancel(ctx)
	defer cancel()
	var wg sync.WaitGroup
	var clients []client.Client
	var cmu sync.Mutex
	start := time.Now()
	n := 0
	for r := range p.Rooms {
		for i := range p.Publishers + p.Subscribers {
			publisher := i < p.Publishers
			identity := fmt.Sprintf("lt-%d-%d", r, i)
			wg.Add(1)
			go func() {
				defer wg.Done()
				c, err := startClient(runCtx, p, fmt.Sprintf("loadtest-%d", r), identity, publisher, col, logger)
				if err != nil {
					col.connectFail.Add(1)
					logger.Warn("client failed", "identity", identity, "err", err)
					return
				}
				cmu.Lock()
				clients = append(clients, c)
				cmu.Unlock()
			}()
			n++
			select {
			case <-time.After(gap):
			case <-ctx.Done():
			}
		}
	}
	fmt.Printf("ramp-up done: %d clients in %s\n", n, time.Since(start).Round(time.Millisecond))

	measureStart := time.Now()
	startPkts, startBytes := col.rxPkts.Load(), col.rxBytes.Load()
	tick := time.NewTicker(p.ReportPeriod)
	end := time.After(p.Duration)
	lastPkts, lastBytes, lastT := startPkts, startBytes, time.Now()
loop:
	for {
		select {
		case <-ctx.Done():
			break loop
		case <-end:
			break loop
		case now := <-tick.C:
			pk, by := col.rxPkts.Load(), col.rxBytes.Load()
			dt := now.Sub(lastT).Seconds()
			col.mu.Lock()
			p50, p99 := pct(col.latencies, 0.5), pct(col.latencies, 0.99)
			col.mu.Unlock()
			fmt.Printf("%6.0fs rx %8.0f pkt/s %7.2f Mbit/s loss %.2f%% latency p50 %.1f ms p99 %.1f ms\n",
				now.Sub(measureStart).Seconds(), float64(pk-lastPkts)/dt, float64(by-lastBytes)*8/dt/1e6,
				lossPct(col), p50, p99)
			lastPkts, lastBytes, lastT = pk, by, now
		}
	}
	tick.Stop()
	dur := time.Since(measureStart).Seconds()
	col.mu.Lock()
	rep := Report{
		Clients: len(clients), ConnectFailures: int(col.connectFail.Load()),
		JoinMsP50: pct(col.joins, 0.5), JoinMsP95: pct(col.joins, 0.95), FirstPacketP95: pct(col.firsts, 0.95),
		RxPackets: col.rxPkts.Load() - startPkts, LossPercent: lossPct(col),
		LatencyMsP50: pct(col.latencies, 0.5), LatencyMsP99: pct(col.latencies, 0.99), DurationSec: dur,
	}
	col.mu.Unlock()
	rep.RxPPS = float64(rep.RxPackets) / dur
	rep.RxMbps = float64(col.rxBytes.Load()-startBytes) * 8 / dur / 1e6
	cancel()
	for _, c := range clients {
		_ = c.Disconnect(context.Background())
	}
	wg.Wait()
	out, _ := json.MarshalIndent(rep, "", "  ")
	fmt.Println(string(out))
	if p.JSON != "" {
		if err := os.WriteFile(p.JSON, out, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func lossPct(c *collector) float64 {
	exp := c.expected.Load()
	if exp == 0 {
		return 0
	}
	return float64(c.lost.Load()) * 100 / float64(exp)
}

func startClient(ctx context.Context, p Params, roomName, identity string, publisher bool, col *collector, logger *slog.Logger) (client.Client, error) {
	g := &auth.RoomGrant{Room: roomName, RoomJoin: true}
	if !publisher {
		g.CanPublish = auth.Bool(false)
	}
	tok, err := auth.NewAccessToken(p.APIKey, p.Secret).SetIdentity(identity).SetGrant(g).ToJWT()
	if err != nil {
		return nil, err
	}
	opts := client.Options{AutoSubscribe: true, SDK: tesserav1.ClientInfo_SDK_LOADTEST, Logger: logger}
	if p.Loopback {
		opts.SettingEngine = client.LoopbackSettingEngine()
	}
	c := client.New(opts)
	t0 := time.Now()
	var first atomic.Bool
	c.SetCallbacks(client.Callbacks{OnTrackSubscribed: func(rt *client.RemoteTrack) {
		go receive(rt, col, func() {
			if first.CompareAndSwap(false, true) {
				col.mu.Lock()
				col.firsts = append(col.firsts, float64(time.Since(t0).Milliseconds()))
				col.mu.Unlock()
			}
		})
	}})
	cctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	if err := c.Connect(cctx, p.URL, tok); err != nil {
		return nil, err
	}
	col.mu.Lock()
	col.joins = append(col.joins, float64(time.Since(t0).Milliseconds()))
	col.mu.Unlock()
	if publisher {
		if err := publish(ctx, cctx, c, identity, p); err != nil {
			_ = c.Disconnect(context.Background())
			return nil, err
		}
	}
	return c, nil
}

func publish(runCtx, ctx context.Context, c client.Client, id string, p Params) error {
	audio, err := webrtc.NewTrackLocalStaticRTP(webrtc.RTPCodecCapability{MimeType: webrtc.MimeTypeOpus, ClockRate: 48000, Channels: 2}, id+"-mic", id)
	if err != nil {
		return err
	}
	if _, err := c.PublishTrack(ctx, audio, client.PublishOptions{Name: "mic"}); err != nil {
		return err
	}
	go sendAudio(runCtx, audio)
	if p.AudioOnly {
		return nil
	}
	rids := []string{"q", "h", "f"}[3-p.VideoLayers:]
	sizes := []int{180, 600, 1100}[3-p.VideoLayers:]
	var tracks []*webrtc.TrackLocalStaticRTP
	var locals []webrtc.TrackLocal
	for _, rid := range rids {
		var opt []func(*webrtc.TrackLocalStaticRTP)
		if p.VideoLayers > 1 {
			opt = append(opt, webrtc.WithRTPStreamID(rid))
		}
		t, err := webrtc.NewTrackLocalStaticRTP(webrtc.RTPCodecCapability{MimeType: webrtc.MimeTypeVP8, ClockRate: 90000}, id+"-cam", id, opt...)
		if err != nil {
			return err
		}
		tracks = append(tracks, t)
		locals = append(locals, t)
	}
	if _, err := c.PublishSimulcastTrack(ctx, locals, client.PublishOptions{Name: "cam", Width: 1280, Height: 720}); err != nil {
		return err
	}
	for i, t := range tracks {
		go sendVideo(runCtx, t, sizes[i])
	}
	return nil
}

func stamp(b []byte) {
	b[0], b[1] = magic[0], magic[1]
	binary.BigEndian.PutUint64(b[2:], uint64(time.Now().UnixNano()))
}

func sendAudio(ctx context.Context, t *webrtc.TrackLocalStaticRTP) {
	tk := time.NewTicker(20 * time.Millisecond)
	defer tk.Stop()
	pkt := &rtp.Packet{Header: rtp.Header{Version: 2, Marker: true}, Payload: make([]byte, 80)}
	for {
		select {
		case <-ctx.Done():
			return
		case <-tk.C:
			stamp(pkt.Payload)
			_ = t.WriteRTP(pkt)
			pkt.SequenceNumber++
			pkt.Timestamp += 960
		}
	}
}

// sendVideo sends 30 fps VP8 frames of 2 packets of size bytes, with a
// 15-bit picture id, TL0PICIDX and a keyframe every 2 s.
func sendVideo(ctx context.Context, t *webrtc.TrackLocalStaticRTP, size int) {
	tk := time.NewTicker(33 * time.Millisecond)
	defer tk.Stop()
	var sn, pid uint16
	var ts uint32
	var tl0 uint8
	frame := 0
	payload := make([]byte, size)
	for {
		select {
		case <-ctx.Done():
			return
		case <-tk.C:
			key := frame%60 == 0
			for i := range 2 {
				s := byte(0)
				if i == 0 {
					s = 0x10
				}
				hdr := byte(0x01)
				if key {
					hdr = 0x00
				}
				copy(payload, []byte{0x80 | s, 0xC0, 0x80 | byte(pid>>8), byte(pid), tl0, hdr})
				stamp(payload[6:])
				_ = t.WriteRTP(&rtp.Packet{Header: rtp.Header{Version: 2, SequenceNumber: sn, Timestamp: ts, Marker: i == 1}, Payload: payload})
				sn++
			}
			frame++
			ts += 3000
			pid = (pid + 1) & 0x7fff
			tl0++
		}
	}
}

// receive reads a remote track, counting packets, SN-gap loss and latency.
func receive(rt *client.RemoteTrack, col *collector, onFirst func()) {
	buf := make([]byte, 1500)
	video := rt.Codec().MimeType == webrtc.MimeTypeVP8
	var last uint16
	started := false
	var p rtp.Packet
	var d buffer.VP8Descriptor
	for {
		n, err := rt.Read(buf)
		if err != nil {
			return
		}
		if p.Unmarshal(buf[:n]) != nil {
			continue
		}
		onFirst()
		col.rxPkts.Add(1)
		col.rxBytes.Add(uint64(n))
		if started {
			if diff := p.SequenceNumber - last; diff > 0 && diff < 1000 {
				col.expected.Add(uint64(diff))
				col.lost.Add(uint64(diff - 1))
				last = p.SequenceNumber
			}
		} else {
			started, last = true, p.SequenceNumber
			col.expected.Add(1)
		}
		pl := p.Payload
		if video {
			if buffer.ParseVP8(pl, &d) != nil || len(pl) < d.HeaderSize+11 {
				continue
			}
			pl = pl[d.HeaderSize+1:]
		}
		if len(pl) >= 10 && pl[0] == magic[0] && pl[1] == magic[1] {
			sent := int64(binary.BigEndian.Uint64(pl[2:]))
			col.latency(float64(time.Now().UnixNano()-sent) / 1e6)
		}
	}
}
